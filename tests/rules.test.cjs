const test = require('node:test')
const assert = require('node:assert/strict')
const { calculateMaxHp, calculateAC, calculateSpeed, calculateProficiencyBonus } = require('../lib/calculations')
const { applyASIs } = require('../lib/asiCalculator')
const { getSpellSlotInfo, getSpellSlots } = require('../lib/spellSlots')
const { getSpellsForClass, getClassFeatures, getSubclassFeatures, getRacialAbilityBonuses, getHydratedRaceInfo } = require('../lib/dndApi')
const stats = { str: 19, dex: 8, con: 14, int: 10, wis: 16, cha: 10 }

test('HP applies constitution retroactively and awards at least one HP per added level', () => {
  assert.equal(calculateMaxHp('Wizard', 5, 2), 32)
  assert.equal(calculateMaxHp('Wizard', 5, -5), 5)
  assert.equal(calculateProficiencyBonus(5), 3)
  assert.equal(calculateProficiencyBonus(20), 6)
})
test('ASI spends both points when primary ability starts at 19', () => {
  const result = applyASIs(stats, 'Fighter', 4)
  assert.equal(result.str, 20)
  assert.equal(result.con, 15)
  assert.equal(stats.str, 19)
})
test('armor respects negative dexterity, heavy armor and shield restrictions', () => {
  assert.equal(calculateAC(stats, 'Fighter', { armor: 'plate' }), 18)
  assert.equal(calculateAC(stats, 'Fighter', { armor: 'hide', shield: true }), 13)
  assert.equal(calculateAC(stats, 'Monk'), 12)
  assert.equal(calculateAC(stats, 'Monk', { shield: true }), 11)
  assert.equal(calculateSpeed('Tabaxi'), 30)
  assert.equal(calculateSpeed('Centaur'), 40)
  assert.equal(calculateSpeed('Human (Standard)', 'Monk', 18), 60)
})
test('spell slots follow full, half, third and pact class tables', () => {
  assert.deepEqual(getSpellSlots('Wizard', '', 5), [4, 3, 2])
  assert.deepEqual(getSpellSlots('Paladin', '', 1), [])
  assert.equal(getSpellSlotInfo('Paladin', '', 1, 3).spellsPrepared, 0)
  assert.deepEqual(getSpellSlots('Artificer', '', 1), [2])
  assert.equal(getSpellSlotInfo('Artificer', '', 1, 3).maxSpellLevel, 1)
  assert.deepEqual(getSpellSlots('Fighter', 'Eldritch Knight', 3), [2])
  assert.deepEqual(getSpellSlots('Fighter', 'Eldritch Knight', 7), [4, 2])
  assert.equal(getSpellSlotInfo('Fighter', 'Eldritch Knight', 20, 3).cantripsKnown, 3)
  assert.equal(getSpellSlotInfo('Rogue', 'Arcane Trickster', 3, 3).cantripsKnown, 3)
  assert.deepEqual(getSpellSlots('Warlock', '', 11), [0, 0, 0, 0, 3])
  assert.deepEqual(getSpellSlotInfo('Warlock', '', 17, 4).mysticArcanum, [6, 7, 8, 9])
})
test('spell lists enforce actual class membership, including third casters and no paladin cantrips', async () => {
  const wizard = (await getSpellsForClass('Wizard', '', 5)).map(s => s.name)
  assert.ok(wizard.includes('Fireball'))
  assert.ok(!wizard.includes('Cure Wounds'))
  const cleric = (await getSpellsForClass('Cleric', '', 5)).map(s => s.name)
  assert.ok(cleric.includes('Cure Wounds'))
  assert.ok(!cleric.includes('Fireball'))
  assert.ok((await getSpellsForClass('Paladin', '', 5)).every(s => s.level > 0))
  assert.ok(!(await getSpellsForClass('Fighter', 'Eldritch Knight', 3)).some(s => s.name === 'Cure Wounds'))
})
test('features include earned features rather than every unselected option', async () => {
  const names = (await getClassFeatures('Fighter', 1)).map(f => f.name)
  assert.deepEqual(names, ['Fighting Style', 'Second Wind'])
  assert.deepEqual(await getSubclassFeatures('Fighter', 'Champion', 2), [])
  assert.ok((await getSubclassFeatures('Fighter', 'Champion', 3)).some(f => f.name === 'Improved Critical'))
})
test('race hydration merges subrace traits and deterministic racial increases', async () => {
  assert.deepEqual(await getRacialAbilityBonuses('Human (Standard)', 'Fighter'), {str:1,con:1,dex:1,wis:1,cha:1,int:1})
  assert.deepEqual(await getRacialAbilityBonuses('Dwarf (Mountain)', 'Fighter'), {str:2,con:2})
  const hill = await getHydratedRaceInfo('Dwarf (Hill)')
  assert.ok(hill.traits.some(t => t.name === 'Dwarven Toughness'))
})

test('racial and subclass HP grants stack per level and armor affects movement', () => {
  assert.equal(calculateMaxHp('Sorcerer', 5, 2, { race: 'Dwarf (Hill)', subclass: 'Draconic Bloodline' }), 42)
  assert.equal(calculateSpeed('Human (Standard)', 'Fighter', 5, { armor: 'plate', strength: 14 }), 20)
  assert.equal(calculateSpeed('Dwarf (Hill)', 'Fighter', 5, { armor: 'plate', strength: 8 }), 25)
  assert.equal(calculateSpeed('Human (Standard)', 'Monk', 6, { armor: 'leather' }), 30)
  assert.equal(calculateSpeed('Human (Standard)', 'Barbarian', 5, { armor: 'plate', strength: 16 }), 30)
  assert.equal(calculateAC(stats, 'Sorcerer', {subclass: 'Draconic Bloodline'}), 12)
  assert.equal(calculateAC(stats, 'Fighter', {race: 'Tortle', shield: true}), 19)
})
test('subclass spell grants respect levels, expansion versus known and explicit choices', async () => {
  const { getSubclassSpellGrants } = require('../lib/dndApi')
  const life = await getSubclassSpellGrants('Cleric', 'Life Domain', 1)
  assert.deepEqual(life.prepared, ['Bless', 'Cure Wounds'])
  const fiend = await getSubclassSpellGrants('Warlock', 'The Fiend', 5)
  assert.ok(fiend.expanded.includes('Fireball'))
  assert.equal(fiend.known.length, 0)
  const sorcerer = await getSpellsForClass('Sorcerer', 'Aberrant Mind', 1)
  assert.ok(sorcerer.some(s => s.name === 'Mind Sliver' && s.grantedBySubclass === 'known'))
  const land = await getSubclassSpellGrants('Druid', 'Circle of the Land', 5)
  assert.equal(land.prepared.length, 0)
  const arctic = await getSubclassSpellGrants('Druid', 'Circle of the Land', 5, 'Arctic')
  assert.ok(arctic.prepared.includes('Slow'))
  assert.ok(!arctic.prepared.includes('Haste'))
  assert.ok((await getSpellsForClass('Sorcerer', 'Divine Soul', 1)).some(s => s.name === 'Cure Wounds'))
  assert.ok((await getSubclassFeatures('Fighter', 'Purple Dragon Knight', 3)).length > 0)
})
